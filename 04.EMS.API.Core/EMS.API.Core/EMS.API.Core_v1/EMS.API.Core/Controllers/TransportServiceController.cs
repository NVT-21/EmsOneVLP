        [Route("GetByID")]
        public ZResponse GetByID(int ID)
        {
            ZResponse res = new ZResponse();
            try
            {
                int result = -1;
                ZTransportServiceGetByIDResponse item = null;
                using (DbCommand dbCommand = XHelper.Database.GetStoredProcCommand(XHelper.Schema + "EMS_TRANSPORT_SERVICE_PKG.GET_BY_ID", new object[]
                {
                    ID, //P_ID          NUMBER
                    0,  //P_RETURN_CODE OUT NUMBER
                    0   //P_OUT_CURSOR  OUT T_CURSOR
                }))
                {
                    result = XHelper.ExecuteNonQuery(dbCommand);
                    if (result >= 0)
                    {
                        result = Convert.ToInt32(dbCommand.Parameters["P_RETURN_CODE"].Value);
                        if (result > 0)
                        {
                            using (IDataReader dr = (IDataReader)dbCommand.Parameters["P_OUT_CURSOR"].Value)
                            {
                                if (dr.Read())
                                {
                                    item = new ZTransportServiceGetByIDResponse()
                                    {
                                        ID = Convert.ToInt32(dr["ID"]),
                                        ParentID = Convert.ToInt32(dr["PARENT_ID"]),
                                        Code = dr["CODE"].ToString(),
                                        Name = dr["NAME"].ToString(),
                                        Classification = dr["CLASSIFICATION"].ToString(),
                                        Type = Convert.ToInt32(dr["TYPE"]),
                                        IsSpecial = dr["SPECIAL_SERVICE"].ToString(),
                                        Description = dr["DESCRIPTION"].ToString(),
                                        CreatedBy = Convert.ToInt32(dr["CREATED_BY"]),
                                        CreatedDate = dr["CREATED_DATE"].ToString()
                                    };
                                }
                            }
                            if (item != null)
                            {
                                res.Code = "00";
                                res.Message = "Thành công.";
                                res.Data = JsonConvert.SerializeObject(item);
                            }
                            else
                            {
                                res.Code = "01";
                                res.Message = "Dữ liệu không tồn tại.";
                            }
                        }
                        else
                        {
                            res.Code = "99";
                            res.Message = "Thất bại.";
                        }
                    }
                    else
                    {
                        res.Code = "99";
                        res.Message = "Lỗi hệ thống, vui lòng liên hệ quản trị.";
                    }
                }
            }
            catch (Exception ex)
            {
                XHelper.LogToFile(LogFileType.EXCEPTION, "TransportServiceController.GetByID: " + ex.Message);
                res.Code = "99";
                res.Message = "Lỗi hệ thống, vui lòng liên hệ quản trị.";
            }
            res.Time = DateTime.Now.ToString("dd/MM/yyyy HH:mm:ss");
            return res;
        }

