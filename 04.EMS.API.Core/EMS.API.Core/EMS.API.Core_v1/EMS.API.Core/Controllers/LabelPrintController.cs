        [Route("GetByID")]
        public ZResponse GetByID(int ShopID, int LabelPrintID)
        {
            ZResponse res = new ZResponse();
            try
            {
                int result = -1;
                ZLabelPrintGetByIDResponse item = null;
                using (DbCommand dbCommand = XHelper.Database.GetStoredProcCommand(XHelper.Schema + "EMS_LABEL_PRINT_PKG.GET_BY_ID", new object[]
                {
                    LabelPrintID,
                    ShopID,
                    0,
                    0
                }))
                {
                    result = XHelper.ExecuteNonQuery(dbCommand);
                    if (result >= 0)
                    {
                        result = Convert.ToInt32(dbCommand.Parameters["P_RETURN_CODE"].Value);
                        if (result > 0)
                        {
                            using (IDataReader dr = (IDataReader)dbCommand.Parameters["P_OUT_CURSOR"].Value)
                            {
                                if (dr.Read())
                                {
                                    item = new ZLabelPrintGetByIDResponse()
                                    {
                                        LabelPrintID = Convert.ToInt32(dr["LABEL_PRINT_ID"]),
                                        LabelName = Convert.ToString(dr["LABEL_NAME"]),
                                        FullName = Convert.ToString(dr["FULL_NAME"]),
                                        MobileNumber = Convert.ToString(dr["MOBILE_NUMBER"]),
                                        ProvinceID = Convert.ToInt32(dr["PROVINCE_ID"]),
                                        DistrictID = Convert.ToInt32(dr["DISTRICT_ID"]),
                                        WardID = Convert.ToInt32(dr["WARD_ID"]),
                                        Street = Convert.ToString(dr["STREET"]),
                                        FullAddress = Convert.ToString(dr["FULL_ADDRESS"]),
                                        PickUpAddressID = Convert.ToInt32(dr["PICK_UP_ADDRESS_ID"]),
                                        ShopID = Convert.ToInt32(dr["SHOP_ID"]),
                                        IsDefault = Convert.ToString(dr["IS_DEFAULT"])
                                    };
                                }
                            }
                            if (item != null)
                            {
                                res.Code = "00";
                                res.Message = "Thành công.";
                                res.Data = JsonConvert.SerializeObject(item);
                            }
                            else
                            {
                                res.Code = "01";
                                res.Message = "Không tồn tại dữ liệu.";
                                res.Data = null;
                            }
                        }
                        else
                        {
                            res.Code = "99";
                            res.Message = "Thất bại.";
                        }
                    }
                    else
                    {
                        res.Code = "99";
                        res.Message = "Lỗi hệ thống. Vui lòng liên hệ quản trị.";
                    }
                }
            }
            catch (Exception ex)
            {
                XHelper.LogToFile(LogFileType.EXCEPTION, "LabelPrintController.GetByID " + ex.Message);
                res.Code = "99";
                res.Message = "Lỗi hệ thống. Vui lòng liên hệ quản trị.";
            }
            res.Time = DateTime.Now.ToString("dd/MM/yyyy HH:mm:ss");
            return res;
        }

