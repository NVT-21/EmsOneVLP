using System;
using System.Collections.Generic;
using System.Linq;
using System.Web;
using EMS.Library;
using EMS.Entity;
using EMS.Core;
using System.Data.Common;
using System.Web.Http;
using System.Data;
using Newtonsoft.Json;

namespace EMS.API.Core.Controllers
{
    [RoutePrefix("Excel")]
    public class ExcelController : ApiController
    {
        [Route("AddImportExcel")]
        public ZResponse AddImportExcel(ZImportExcelRequest req)
        {
            int result = -1;
            ZResponse res = new ZResponse();
            try
            {
                using (DbCommand dbCommand = XHelper.Database.GetStoredProcCommand(XHelper.Schema + "EMS_IMPORT_EXCEL_PKG.ADD_IMPORT_EXCEL", new object[]
                {
                    0,
                    req.ShopID,
                    req.FileName,
                    req.TotalRow,
                    req.FunctionName,
                    req.CreatedBy,
                    req.ImportVersion,
                    0
                }))
                {
                    result = XHelper.ExecuteNonQuery(dbCommand);
                    if (result >= 0)
                    {
                        result = Convert.ToInt32(dbCommand.Parameters[0].Value);
                        if (result > 0)
                        {
                            res.Code = "00";
                            res.Message = "Thêm mới thành công.";
                            res.Data = JsonConvert.SerializeObject(new { ImportCode = dbCommand.Parameters["P_OUT_IMPORT_CODE"].Value.ToString() });
                        }
                        else
                        {
                            res.Code = "99";
                            res.Message = "Thất bại";
                        }
                    }
                    else
                    {
                        res.Code = "99";
                        res.Message = "Lỗi hệ thống, vui lòng liên hệ quản trị.";
                    }
                }
            }
            catch (Exception ex)
            {
                XHelper.LogToFile(LogFileType.EXCEPTION, "ExcelController.AddImportExcel: " + ex.Message);
                res.Code = "99";
                res.Message = "Lỗi hệ thống, vui lòng liên hệ quản trị.";
            }
            res.Time = DateTime.Now.ToString("dd/MM/yyyy HH:mm:ss");
            return res;
        }
    }
}