        public static ZResponse UpdateCustomerGroup(int DeliveryNoteID)
        {
            int result = -1;
            ZResponse res = new ZResponse();
            try
            {
                using (DbCommand dbCommand = XHelper.Database.GetStoredProcCommand(XHelper.Schema + "EMS_CUSTOMER_PKG.UPDATE_CUSTOMER_GROUP", new object[]
                {
                    0,
                    DeliveryNoteID
                }))
                {
                    result = XHelper.ExecuteNonQuery(dbCommand);
                    if (result >= 0)
                    {
                        result = Convert.ToInt32(dbCommand.Parameters[0].Value);
                        if (result > 0)
                        {
                            res.Code = "00";
                            res.Message = "Cập nhật nhóm khách hàng thành công.";
                        }
                        else
                        {
                            switch (result)
                            {
                                case -1:
                                    res.Code = "01";
                                    res.Message = "Dữ liệu không tồn tại.";
                                    break;
                                case -2:
                                    res.Code = "02";
                                    res.Message = "Giống nhau nên không update";
                                    break;
                                default:
                                    res.Code = "99";
                                    res.Message = "Thất bại";
                                    XHelper.LogToFile(LogFileType.MESSAGE, "CustomerRepository.UpdateCustomerGroup: 99, Thất bại");
                                    break;
                            }
                        }
                    }
                    else
                    {
                        XHelper.LogToFile(LogFileType.MESSAGE, "CustomerRepository.UpdateCustomerGroup: 99, Lỗi hệ thống");
                        res.Code = "99";
                        res.Message = "Lỗi hệ thống, vui lòng liên hệ quản trị.";
                    }
                }
            }
            catch (Exception ex)
            {
                XHelper.LogToFile(LogFileType.EXCEPTION, "CustomerRepository.UpdateCustomerGroup: " + ex.Message);
                res.Code = "99";
                res.Message = "Lỗi hệ thống, vui lòng liên hệ quản trị.";
            }
            res.Time = DateTime.Now.ToString("dd/MM/yyyy HH:mm:ss");
            return res;
        }

        public static ZResponse IsExist(ZCustomerIsExistRequest req)
        {
            ZResponse res = new ZResponse();
            try
            {
                int result = -1;
                using (DbCommand dbCommand = XHelper.Database.GetStoredProcCommand(XHelper.Schema + "EMS_CUSTOMER_PKG.IS_EXIST", new object[]
                {
                    0,
                    req.MobileNumber,
                    req.FullName,
                    req.ProvinceID,
                    //req.DistrictID,
                    req.WardID,
                    req.Street,
                    req.ShopID,
                    req.CreatedBy,
                    req.Channel,
                    string.IsNullOrEmpty(XHelper.DeviceName) ? req.DeviceName : XHelper.DeviceName,
                    req.IsUpdated,
                    0
                }))
                {
                    result = XHelper.ExecuteNonQuery(dbCommand);
                    if (result >= 0)
                    {
                        result = Convert.ToInt32(dbCommand.Parameters[0].Value);
                        if (result > 0)
                        {
                            res.Code = "00";
                            res.Message = "Thành công.";
                            res.Data = dbCommand.Parameters["P_OUT_CUSTOMER_ID"].Value.ToString();
                        }
                        else
                        {
                            switch (result)
                            {
                                default:
                                    res.Code = "99";
                                    res.Message = "Thất bại.";
                                    break;
                            }
                        }
                    }
                    else
                    {
                        res.Code = "99";
                        res.Message = "Lỗi hệ thống, vui lòng liên hệ quản trị.";
                    }
                }
            }
            catch (Exception ex)
            {
                XHelper.LogToFile(LogFileType.EXCEPTION, "CustomerRepository.IsExist " + ex.Message);
                res.Code = "99";
                res.Message = "Lỗi hệ thống, vui lòng liên hệ quản trị.";
            }
            res.Time = DateTime.Now.ToString("dd/MM/yyyy HH:mm:ss");
            return res;
        }
